import { test, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';

test('rate-limit recovery stays in the import dialog and preserves the URL on a narrow screen', async ({ page }) => {
    await page.goto('/#skills');
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('link', { name: 'Skill 库', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.route('**/api/skills/discover', route => route.fulfill({ status: 429, json: { error: 'GitHub 来源请求已限流，请在 2026/10/30 18:00:00（北京时间）后重试' } }));
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/pmspec');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog).toContainText('2026/10/30 18:00:00（北京时间）');
    await expect(dialog.getByLabel('Skill URL')).toHaveValue('https://github.com/example/pmspec');
    await expect(dialog.getByRole('button', { name: '导入', exact: true })).toBeEnabled();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.unroute('**/api/skills/discover');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true })).toBeVisible();
});

test('suite selection, partial failure and retry import independent skills without repeating successes', async ({ page }) => {
    await page.goto('/#skills');
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('link', { name: 'Skill 库', exact: true }).click();
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/pmspec');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true })).toBeVisible();
    await expect(dialog.getByRole('button', { name: '导入所选（0）', exact: true })).toBeDisabled();
    await expect(page.getByRole('link', { name: 'pmspec-apply', exact: true })).toHaveCount(0);
    for (const [width, theme] of [[1280, 'japan-blues'], [390, 'cyberpunk'], [320, 'japan-blues']] as const) {
        await page.setViewportSize({ width, height: 844 });
        await page.evaluate(value => document.documentElement.dataset.theme = value, theme);
        await expect(dialog.getByLabel('Skill URL')).toBeVisible();
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
        await page.screenshot({ path: '.local/multi-skills-' + width + '.png', fullPage: true, animations: 'disabled' });
        await dialog.getByRole('checkbox', { name: '导入 pmspec-review', exact: true }).scrollIntoViewIfNeeded();
        await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-review', exact: true })).toBeInViewport();
        await expect(dialog.getByRole('button', { name: '导入所选（0）', exact: true })).toBeInViewport();
        await dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true }).scrollIntoViewIfNeeded();
    }
    await page.setViewportSize({ width: 1280, height: 844 });
    await dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true }).check();
    await dialog.getByRole('checkbox', { name: '导入 pmspec-review', exact: true }).check();
    let partial = true;
    const submitted: string[][] = [];
    await page.route('**/api/skills/import-batch', async route => {
        const body = route.request().postDataJSON();
        submitted.push(body.items.map((item: { path: string }) => item.path));
        if (!partial) return route.continue();
        partial = false;
        const response = await route.fetch({ postData: JSON.stringify({ ...body, items: body.items.filter((item: { path: string }) => !item.path.endsWith('review')) }) });
        const value = await response.json();
        value.results.push({ path: 'skills/pmspec-review', status: 'failed', error: '专用失败样例，请重试' });
        await route.fulfill({ response, json: value });
    });
    await dialog.getByRole('button', { name: '导入所选（2）', exact: true }).click();
    await expect(dialog).toContainText('专用失败样例');
    await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true })).toBeDisabled();
    await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-review', exact: true })).toBeChecked();
    await dialog.getByText('专用失败样例，请重试', { exact: true }).scrollIntoViewIfNeeded();
    await expect(dialog.getByText('专用失败样例，请重试', { exact: true })).toBeInViewport();
    await page.screenshot({ path: '.local/multi-skills-partial-1280.png', fullPage: true, animations: 'disabled' });
    await dialog.getByRole('button', { name: '重试所选（1）', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    expect(submitted[1]).toEqual(['skills/pmspec-review']);
    await expect(page.getByRole('link', { name: 'pmspec-apply', exact: true })).toHaveCount(1);
    await expect(page.getByRole('link', { name: 'pmspec-review', exact: true })).toHaveCount(1);
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/pmspec/tree/main/skills');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await dialog.getByRole('checkbox', { name: '选择全部候选 Skill', exact: true }).check();
    for (const name of ['apply', 'review']) {
        await dialog.getByRole('combobox', { name: 'pmspec-' + name + ' 冲突处理', exact: true }).click();
        await page.getByRole('option', { name: '跳过', exact: true }).click();
    }
    await dialog.getByRole('button', { name: '导入所选（5）', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    for (const name of ['apply', 'review', 'explore', 'init', 'propose']) await expect(page.getByRole('link', { name: 'pmspec-' + name, exact: true })).toHaveCount(1);
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/pmspec');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true }).check();
    await dialog.getByRole('combobox', { name: 'pmspec-apply 冲突处理', exact: true }).click();
    await page.getByRole('option', { name: '覆盖原条目', exact: true }).click();
    const requestsBeforeConfirmation = submitted.length;
    await dialog.getByRole('button', { name: '导入所选（1）', exact: true }).click();
    await expect(page.getByRole('alertdialog')).toContainText('替换 pmspec-apply');
    await page.screenshot({ path: '.local/multi-skills-conflict-1280.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click();
    expect(submitted.length).toBe(requestsBeforeConfirmation);
    await expect(dialog.getByRole('checkbox', { name: '导入 pmspec-apply', exact: true })).toBeChecked();
    await dialog.getByRole('button', { name: '导入所选（1）', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: '覆盖所选', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    expect(submitted.length).toBe(requestsBeforeConfirmation + 1);
    await expect(page.getByRole('link', { name: 'pmspec-apply', exact: true })).toHaveCount(1);
    await page.getByRole('link', { name: 'pmspec-init', exact: true }).click();
    await page.getByRole('tab', { name: /文件/ }).click();
    await page.getByRole('button', { name: 'references/note.md', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Reference init-note', exact: true })).toBeVisible();
    await page.screenshot({ path: '.local/multi-skills-file-1280.png', fullPage: true, animations: 'disabled' });
    await writeFile('.local/multi-skills-detail-url.txt', page.url());
});
