import { test, expect } from '@playwright/test';

test('Skill uses themed accessible selection, menu and dialog components without changing the workflow', async ({ page }) => {
    await page.goto('/#skills');
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    const sort = page.getByRole('combobox', { name: '排序', exact: true });
    await sort.click();
    const options = page.getByRole('listbox');
    await expect(options).toBeVisible();
    await expect(options).toHaveCSS('background-color', 'oklch(1 0 0)');
    await expect(options).toHaveCSS('opacity', '1');
    await page.screenshot({ path: '.local/skill-shadcn-select.png', fullPage: false });
    await page.getByRole('option', { name: '名称升序', exact: true }).click();
    await expect(sort).toHaveText('名称升序');
    const trigger = page.getByRole('button', { name: '从 URL 导入', exact: true });
    await expect(trigger).toHaveCSS('background-color', 'oklch(0.704 0.04 256.788)');
    await trigger.click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toHaveCSS('background-color', 'oklch(0.9818 0.0054 95.0986)');
    await expect(dialog).toHaveCSS('opacity', '1');
    await page.screenshot({ path: '.local/skill-shadcn-dialog.png', fullPage: false });
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/components');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await page.getByRole('button', { name: 'components 操作', exact: true }).click();
    const menu = page.getByRole('menu');
    await expect(menu).toBeVisible();
    await expect(menu).toHaveCSS('background-color', 'oklch(1 0 0)');
    await expect(menu).toHaveCSS('opacity', '1');
    await page.screenshot({ path: '.local/skill-shadcn-menu.png', fullPage: false });
    await expect(menu.getByRole('menuitem', { name: '新标签打开', exact: true })).toHaveAttribute('href', /#skill\//);
    await page.keyboard.press('Escape');
    await expect(menu).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'components 操作', exact: true })).toBeFocused();
    const checkbox = page.getByRole('checkbox', { name: '选择 components', exact: true });
    await checkbox.check();
    await expect(checkbox).toBeChecked();
    await expect(checkbox).toHaveCSS('background-color', 'oklch(0.704 0.04 256.788)');
    await expect(page.getByRole('toolbar', { name: '所选 Skill 操作' })).toBeVisible();
    await page.getByRole('button', { name: '取消选择', exact: true }).click();
    await page.getByRole('link', { name: 'components', exact: true }).click();
    await page.getByRole('tab', { name: '概览', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: /文件/ })).toHaveAttribute('aria-selected', 'true');
    await expect(page.getByRole('tabpanel')).toContainText('Writer guide');
    await expect(page.getByRole('heading', { name: 'Writer guide' })).toBeVisible();
});
