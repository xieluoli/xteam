import { test, expect, type Page } from '@playwright/test';
async function login(page: Page) {
    await page.goto('/#skills');
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    if ((page.viewportSize()?.width ?? 1280) < 768) await page.getByRole('button', { name: '切换侧边栏', exact: true }).click();
    await page.getByRole('link', { name: 'Skill 库', exact: true }).click();
}
async function importSkill(page: Page, name: string) {
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/' + name);
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog).toHaveCount(0);
}
test('Skill URL import, independent detail, properties, file tree and safe preview form one persisted workflow', async ({ page }) => {
    await login(page);
    await importSkill(page, 'review');
    await page.getByRole('link', { name: 'review', exact: true }).click();
    await expect(page).toHaveURL(/#skill\//);
    await expect(page.getByRole('heading', { name: 'review', exact: true })).toBeVisible();
    await page.getByLabel('名称', { exact: true }).fill('review-local');
    await page.getByLabel('简介', { exact: true }).fill('Updated by browser');
    await page.getByLabel('标签', { exact: true }).fill('Team, Review');
    await page.getByRole('button', { name: '保存属性', exact: true }).click();
    await page.getByRole('tab', { name: /Files/ }).click();
    await expect(page.getByRole('heading', { name: 'Review guide', exact: true })).toBeVisible();
    await expect(page.locator('.skill-preview img')).toHaveCount(0);
    expect(await page.evaluate(() => (globalThis as { __skillExecuted?: boolean }).__skillExecuted)).toBeUndefined();
    await page.getByRole('button', { name: '编辑文件', exact: true }).click();
    await expect(page.getByLabel('文件正文')).toHaveValue(/name: review-local/);
    await expect(page.getByLabel('文件正文')).toHaveValue(/custom: keep/);
    await page.getByLabel('文件正文').fill('---\nname: review-local\ndescription: From main file\ncustom: keep\n---\n# Edited guide');
    await page.getByRole('button', { name: '保存文件', exact: true }).click();
    await page.getByRole('button', { name: '新增文件', exact: true }).click();
    await page.getByLabel('文件路径', { exact: true }).fill('references/local.md');
    await page.getByLabel('新文件正文').fill('# Local note');
    await page.getByRole('button', { name: '创建文件', exact: true }).click();
    await page.getByRole('button', { name: 'references/local.md', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Local note' })).toBeVisible();
    await page.getByRole('button', { name: 'scripts/demo.html', exact: true }).click();
    await expect(page.locator('.skill-file-content')).toContainText('<script>');
    expect(await page.evaluate(() => (globalThis as { __skillExecuted?: boolean }).__skillExecuted)).toBeUndefined();
    await page.screenshot({ path: '.local/skill-files.png', fullPage: true });
    const detailURL = page.url();
    await page.reload();
    await expect(page.getByRole('heading', { name: 'review-local', exact: true })).toBeVisible();
    await page.getByRole('tab', { name: 'Overview', exact: true }).click();
    await expect(page.getByLabel('简介', { exact: true })).toHaveValue('From main file');
    await expect(page.getByLabel('标签', { exact: true })).toHaveValue('Team, Review');
    await page.screenshot({ path: '.local/skill-overview.png', fullPage: true });
    await page.getByRole('link', { name: '返回 Skill 库', exact: true }).click();
    await expect(page.getByRole('link', { name: 'review-local', exact: true })).toHaveAttribute('href', new URL(detailURL).hash);
    await page.goBack();
    await expect(page.getByRole('heading', { name: 'review-local', exact: true })).toBeVisible();
    await page.goForward();
    await expect(page.getByRole('heading', { name: 'Skill 库', exact: true })).toBeVisible();
    await page.screenshot({ path: '.local/skill-list.png', fullPage: true });
});
test('conflicts, filter/sort and partial batch refresh retain individual failures, then bulk delete removes selected skills', async ({ page }) => {
    await login(page);
    await importSkill(page, 'writer');
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Skill URL').fill('https://github.com/example/writer');
    await dialog.getByRole('button', { name: '导入', exact: true }).click();
    await expect(dialog).toContainText('已有同名 Skill');
    await dialog.getByRole('button', { name: '重命名副本', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    await page.getByRole('combobox', { name: '排序', exact: true }).click();
    await page.getByRole('option', { name: '名称升序', exact: true }).click();
    await page.getByRole('button', { name: '筛选', exact: true }).click();
    await page.getByRole('combobox', { name: '添加者', exact: true }).click();
    await page.getByRole('option', { name: 'browser@example.com', exact: true }).click();
    await expect(page.getByRole('link', { name: 'writer-2', exact: true })).toBeVisible();
    await page.getByLabel('搜索 Skill').fill('writer');
    await page.getByRole('checkbox', { name: '选择 writer', exact: true }).check();
    await page.getByRole('checkbox', { name: '选择 writer-2', exact: true }).check();
    await page.getByRole('button', { name: '更新所选', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: '确认更新', exact: true }).click();
    await expect(page.getByRole('region', { name: '操作结果' })).toContainText('writer：已更新');
    await expect(page.getByRole('region', { name: '操作结果' })).toContainText('writer-2：失败');
    await expect(page.getByRole('link', { name: 'writer-2', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '删除所选', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: '删除 Skill', exact: true }).click();
    await expect(page.getByRole('link', { name: 'writer', exact: true })).toHaveCount(0);
    await expect(page.getByRole('link', { name: 'writer-2', exact: true })).toHaveCount(0);
    await expect(page.getByText('Add to agent', { exact: true })).toHaveCount(0);
    await expect(page.getByText('Used by', { exact: true })).toHaveCount(0);
});

test('import dialog retains keyboard focus while typing and Skill detail fits a narrow viewport', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await login(page);
    await page.getByRole('button', { name: '从 URL 导入', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const input = dialog.getByLabel('Skill URL');
    await input.click();
    await input.pressSequentially('https://github.com/example/review', { delay: 10 });
    await expect(input).toHaveValue('https://github.com/example/review');
    await expect(input).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    await importSkill(page, 'mobile');
    await page.getByRole('link', { name: 'mobile', exact: true }).click();
    await page.getByRole('tab', { name: /Files/ }).click();
    await expect(page.getByRole('heading', { name: 'Writer guide' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({ path: '.local/skill-mobile.png', fullPage: true });
});

test('row menu opens a new tab and single source update and deletion work from detail', async ({ page }) => {
    await login(page);
    await importSkill(page, 'single');
    await page.getByRole('button', { name: 'single 操作', exact: true }).click();
    const popupEvent = page.waitForEvent('popup');
    await page.getByRole('menuitem', { name: '新标签打开', exact: true }).click();
    const popup = await popupEvent;
    await expect(popup.getByRole('heading', { name: 'single', exact: true })).toBeVisible();
    await popup.getByRole('button', { name: '从来源更新', exact: true }).click();
    await popup.getByRole('alertdialog').getByRole('button', { name: '确认更新', exact: true }).click();
    await expect(popup.getByRole('region', { name: '操作结果' })).toContainText('single：已更新');
    await popup.getByRole('button', { name: '删除 Skill', exact: true }).click();
    await popup.getByRole('alertdialog').getByRole('button', { name: '删除 Skill', exact: true }).click();
    await expect(popup.getByRole('heading', { name: 'Skill 库', exact: true })).toBeVisible();
    await expect(popup.getByRole('link', { name: 'single', exact: true })).toHaveCount(0);
    await popup.close();
});
