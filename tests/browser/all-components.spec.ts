import { test, expect } from '@playwright/test';

test('shared sidebar supports mobile navigation and all editors use themed components', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/');
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('button', { name: '切换侧边栏', exact: true }).click();
    const navigation = page.getByRole('dialog');
    await expect(navigation).toBeVisible();
    await navigation.getByRole('link', { name: 'Agent 模板', exact: true }).click();
    await expect(navigation).toHaveCount(0);
    await expect(page.getByRole('heading', { name: 'Agent 模板', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '新建', exact: true }).click();
    const editor = page.getByRole('dialog');
    await editor.getByLabel('名称', { exact: true }).fill('全站组件模板');
    await editor.getByLabel('正文', { exact: true }).fill('# Text only');
    await editor.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('button', { name: '全站组件模板', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click();
    const confirmation = page.getByRole('alertdialog');
    await expect(confirmation).toContainText('永久删除');
    await confirmation.getByRole('button', { name: '取消', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '资源详情' })).toBeVisible();
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: '切换侧边栏', exact: true }).click();
    await page.getByRole('button', { name: '修改密码', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '修改密码' })).toBeVisible();
    await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).first().click();
    await page.getByRole('button', { name: '切换侧边栏', exact: true }).click();
    await page.getByRole('link', { name: 'MCP 接入', exact: true }).click();
    await page.getByLabel('令牌名称').fill('全站组件令牌');
    await page.getByRole('button', { name: '创建令牌' }).click();
    await expect(page.getByLabel('新令牌')).toHaveValue(/^xt_/);
    await page.getByRole('button', { name: '撤销', exact: true }).click();
    await expect(page.getByRole('alertdialog')).toContainText('立即不能访问');
    await page.getByRole('alertdialog').getByRole('button', { name: '撤销令牌', exact: true }).click();
    await expect(page.getByRole('button', { name: '撤销', exact: true })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});

test('desktop pages share the Sidebar and existing project, link, Todo, template and MCP operations remain usable', async ({ page }) => {
    const pageErrors: string[] = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    async function auditControls() {
        const custom = await page.locator('button:visible,input:visible,textarea:visible,select:visible').evaluateAll(elements => elements.filter(element => !element.hasAttribute('data-slot')).map(element => `${element.tagName}: ${element.getAttribute('aria-label') ?? element.textContent}`));
        expect(custom).toEqual([]);
    }
    await page.goto('/');
    await auditControls();
    await page.screenshot({ path: '.local/all-login.png', fullPage: true });
    await page.getByLabel('邮箱', { exact: true }).fill('browser@example.com');
    await page.getByLabel('密码', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page.getByRole('link', { name: '项目', exact: true })).toHaveAttribute('aria-current', 'page');
    await page.getByRole('button', { name: '新建项目', exact: true }).click();
    await auditControls();
    await page.getByLabel('名称', { exact: true }).fill('统一组件验收项目');
    await page.getByLabel('简介', { exact: true }).fill('不改变业务，仅统一 UI。');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('button', { name: '统一组件验收项目', exact: true })).toBeVisible();
    await page.screenshot({ path: '.local/all-project-list.png', fullPage: true });
    await page.getByRole('button', { name: '统一组件验收项目', exact: true }).click();
    await page.getByRole('button', { name: '添加链接', exact: true }).click();
    await page.getByLabel('标题', { exact: true }).fill('统一组件仓库');
    await page.getByLabel('URL', { exact: true }).fill('https://github.com/example/ui');
    await page.getByRole('combobox', { name: '类别', exact: true }).click();
    await page.getByRole('option', { name: 'GitHub', exact: true }).click();
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await expect(page.getByRole('link', { name: /统一组件仓库/ })).toHaveAttribute('href', 'https://github.com/example/ui');
    await page.getByRole('button', { name: '添加 Todo', exact: true }).click();
    await page.getByLabel('标题', { exact: true }).fill('统一组件待办');
    await page.getByLabel('说明 / 结果', { exact: true }).fill('保留结果说明');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByRole('checkbox', { name: '统一组件待办' }).click();
    await expect(page.getByRole('checkbox', { name: '统一组件待办' })).toBeChecked();
    await auditControls();
    await page.screenshot({ path: '.local/all-project-detail.png', fullPage: true });
    await page.getByRole('button', { name: '编辑 / 记录结果' }).click();
    await page.getByLabel('说明 / 结果', { exact: true }).fill('已更新的结果');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await expect(page.getByText('已更新的结果', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '更多项目操作' }).click();
    await page.getByRole('menuitem', { name: '删除项目', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click();
    await expect(page.getByRole('heading', { name: '统一组件验收项目', exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Agent 模板', exact: true }).click();
    await auditControls();
    await page.screenshot({ path: '.local/all-agents.png', fullPage: true });
    await page.getByRole('link', { name: 'Skill 库', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Skill 库', exact: true })).toBeVisible();
    await auditControls();
    await page.screenshot({ path: '.local/all-skills.png', fullPage: true });
    await page.getByRole('link', { name: 'MCP 接入', exact: true }).click();
    await auditControls();
    await page.screenshot({ path: '.local/all-mcp.png', fullPage: true });
    await page.getByRole('button', { name: '修改密码', exact: true }).click();
    await auditControls();
    const password = page.getByRole('dialog', { name: '修改密码', exact: true });
    await expect(password).toHaveCSS('opacity', '1');
    await page.screenshot({ path: '.local/all-password.png' });
    await page.keyboard.press('Escape');
    for (const name of ['项目', 'Agent 模板', 'Skill 库', 'MCP 接入']) {
        await page.setViewportSize({ width: 390, height: 844 });
        await page.getByRole('button', { name: '切换侧边栏', exact: true }).click();
        const sidebar = page.getByRole('dialog');
        await expect(sidebar).toBeVisible();
        await expect(sidebar).toHaveCSS('background-color', 'oklch(0.9663 0.008 98.8792)');
        await expect(sidebar).toHaveCSS('opacity', '1');
        if (name === '项目') {
            await expect.poll(async () => (await sidebar.boundingBox())?.x).toBe(0);
            await page.screenshot({ path: '.local/all-mobile-sidebar.png', animations: 'disabled' });
        }
        await sidebar.getByRole('link', { name, exact: true }).click();
        await expect(sidebar).toHaveCount(0);
        await auditControls();
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    }
    await page.screenshot({ path: '.local/all-mobile-mcp.png', fullPage: true });
    expect(pageErrors).toEqual([]);
});
