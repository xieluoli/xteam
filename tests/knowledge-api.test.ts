import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { createApp } from '../server/app.js';
import { openDatabase, provisionUser } from '../server/store.js';

test('Web, bearer API and MCP share Wiki content, versions and attachment authentication', async () => {
    const directory = mkdtempSync(join(tmpdir(), 'xteam-wiki-api-'));
    const path = join(directory, 'test.db');
    const db = openDatabase(path);
    provisionUser(db, 'wiki-api@example.com', 'wiki-api-password'); db.close();
    const app = createApp({ database: path, origin: 'http://localhost', secure: false });
    const server = app.listen(0, '127.0.0.1');
    await new Promise<void>(resolve => server.once('listening', resolve));
    const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
    const client = new Client({ name: 'wiki-api-test', version: '1' });
    try {
        const login = await fetch(base + '/api/login', { method: 'POST', headers: { Origin: 'http://localhost', 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'wiki-api@example.com', password: 'wiki-api-password' }) });
        const session = await login.json();
        const cookie = login.headers.get('set-cookie')!.split(';')[0];
        const tokenResponse = await fetch(base + '/api/tokens', { method: 'POST', headers: { Origin: 'http://localhost', Cookie: cookie, 'X-CSRF-Token': session.csrf, 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'cli' }) });
        const { token } = await tokenResponse.json();
        const request = async (path: string, method = 'GET', body?: unknown) => {
            const r = await fetch(base + '/api' + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
            return { status: r.status, data: await r.json() };
        };
        const space = await request('/wiki/spaces', 'POST', { name: 'CLI空间' });
        assert.equal(space.status, 201);
        assert.equal((await request('/tokens', 'POST', { name: '不能凭令牌铸造新令牌' })).status, 403);
        const p = await request('/wiki/pages', 'POST', { space_id: space.data.id, title: '可迁移知识', content: 'CLI先写入', kind: 'sop', request_id: 'retry-safe' });
        assert.equal(p.status, 201);
        await client.connect(new StreamableHTTPClientTransport(new URL(base + '/mcp'), { requestInit: { headers: { Authorization: `Bearer ${token}` } } }));
        const result = await client.callTool({ name: 'get_page', arguments: { id: p.data.id } });
        assert.notEqual(result.isError, true);
        assert.equal(JSON.parse((result.content as { text: string }[])[0].text).content, 'CLI先写入');
        assert.equal((await request('/wiki/pages/' + p.data.id, 'PATCH', { content: '需要版本' })).status, 400);
        assert.equal((await request('/wiki/pages/' + p.data.id, 'PATCH', { content: '新内容', expected_version: 1 })).status, 200);
        assert.equal((await request('/wiki/pages/' + p.data.id, 'PATCH', { content: '陈旧内容', expected_version: 1 })).status, 409);
        const a = await request('/wiki/pages/' + p.data.id + '/attachments', 'POST', { name: '研究.pdf', data: Buffer.from('%PDF-1.7 synthetic').toString('base64') });
        assert.equal(a.status, 201);
        assert.equal((await fetch(base + '/api/wiki/attachments/' + a.data.id + '/download')).status, 401);
        const download = await fetch(base + '/api/wiki/attachments/' + a.data.id + '/download', { headers: { Cookie: cookie } });
        assert.equal(await download.text(), '%PDF-1.7 synthetic');
        assert.match(download.headers.get('content-disposition')!, /attachment/);
        const hostile = await fetch(base + '/api/wiki/spaces', { method: 'POST', headers: { Origin: 'https://hostile.example', Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ name: '无权' }) });
        assert.equal(hostile.status, 403);
        assert.equal((await request('/wiki/spaces/' + space.data.id + '/export')).data.schema_version, 1);
        const cli = await promisify(execFile)(process.execPath, ['bin/xteam.mjs', 'search', '新内容', '--json'], { env: { ...process.env, XTEAM_URL: base, XTEAM_TOKEN: token, XTEAM_CONFIG: join(directory, 'cli.json') } });
        const cliResult = JSON.parse(cli.stdout);
        assert.equal(cliResult.schema_version, 1);
        assert.equal(cliResult.data[0].id, p.data.id);
        const missingAuth = await promisify(execFile)(process.execPath, ['bin/xteam.mjs', 'space', 'list', '--json'], { env: { ...process.env, XTEAM_URL: base, XTEAM_TOKEN: '', XTEAM_CONFIG: join(directory, 'cli.json') } }).catch(e => e);
        assert.equal(missingAuth.code, 2);
        assert.equal(JSON.parse(missingAuth.stderr).error.code, 'authentication');
        const env = { ...process.env, XTEAM_URL: base, XTEAM_TOKEN: token, XTEAM_CONFIG: join(directory, 'cli.json') };
        const run = async (args: string[]) => JSON.parse((await promisify(execFile)(process.execPath, ['bin/xteam.mjs', ...args, '--json'], { env })).stdout).data;
        const markdown = join(directory, 'review.md'); writeFileSync(markdown, '# 终端方法\n来源与验收');
        const args = ['page', 'create', '--space', space.data.id, '--title', '终端SOP', '--kind', 'sop', '--file', markdown, '--request-id', 'cli-retry'];
        const created = await run(args);
        assert.equal((await run(args)).id, created.id);
        const localSkill = await run(['skill', 'from-page', created.id, '--expected-version', '1', '--name', 'terminal-review', '--description', '评审时使用']);
        const skillDir = join(directory, 'exported-skill');
        await run(['skill', 'export', localSkill.id, '--output', skillDir]);
        assert.match(readFileSync(join(skillDir, 'SKILL.md'), 'utf8'), /来源与验收/);
        const exported = join(directory, 'exported-space');
        await run(['export', '--space', space.data.id, '--output', exported]);
        assert.equal(readFileSync(join(exported, 'attachments', a.data.id, '研究.pdf'), 'utf8'), '%PDF-1.7 synthetic');
        assert.ok(readFileSync(join(exported, 'pages', created.id + '.md'), 'utf8').includes('终端方法'));
        assert.equal((await run(['page', 'update', created.id, '--file', markdown, '--expected-version', '1'])).version, 2);
        const conflict = await promisify(execFile)(process.execPath, ['bin/xteam.mjs', 'page', 'update', created.id, '--file', markdown, '--expected-version', '1', '--json'], { env }).catch(e => e);
        assert.equal(conflict.code, 4);
        assert.equal(readFileSync(markdown, 'utf8'), '# 终端方法\n来源与验收');
    } finally { await client.close(); await new Promise<void>(resolve => server.close(() => resolve())); app.locals.database.close(); rmSync(directory, { recursive: true, force: true }); }
});
